"""Procedural PBR texture generator for Claude-Smite.

Every texture in public/textures/pbr is generated by this script, so the game
ships with no third-party image assets. Each material is written as two
seamlessly tiling maps (see `save` for the channel layout). Two maps per
material keeps the terrain shader, which blends four materials, under the
WebGPU limit of 16 sampled textures per shader stage.

Usage:  python3 tools/textures/gen.py [--size 1024] [--only flagstone,marble]
Requires numpy and Pillow.
"""

import argparse
import os

import numpy as np
from PIL import Image

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'public', 'textures', 'pbr')


# ---------------------------------------------------------------------------
# Tileable noise primitives
# ---------------------------------------------------------------------------

def _fade(t):
    return t * t * t * (t * (t * 6 - 15) + 10)


def value_noise(size, period, rng):
    """Tileable gradient-ish value noise with `period` cells across the tile."""
    grid = rng.random((period, period)).astype(np.float32)
    coords = np.arange(size, dtype=np.float32) * period / size
    i0 = np.floor(coords).astype(int)
    f = _fade(coords - i0)
    i1 = (i0 + 1) % period
    i0 = i0 % period
    # separable bilinear with quintic fade
    a = grid[np.ix_(i0, i0)]
    b = grid[np.ix_(i0, i1)]
    c = grid[np.ix_(i1, i0)]
    d = grid[np.ix_(i1, i1)]
    fx = f[None, :]
    fy = f[:, None]
    return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy


def value_noise2(size, px, py, rng):
    """Tileable value noise with separate cell counts across X and Y."""
    grid = rng.random((py, px)).astype(np.float32)
    cx = np.arange(size, dtype=np.float32) * px / size
    cy = np.arange(size, dtype=np.float32) * py / size
    x0 = np.floor(cx).astype(int)
    y0 = np.floor(cy).astype(int)
    fx = _fade(cx - x0)[None, :]
    fy = _fade(cy - y0)[:, None]
    x1 = (x0 + 1) % px
    y1 = (y0 + 1) % py
    x0 %= px
    y0 %= py
    a = grid[np.ix_(y0, x0)]
    b = grid[np.ix_(y0, x1)]
    c = grid[np.ix_(y1, x0)]
    d = grid[np.ix_(y1, x1)]
    return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy


def fbm(size, base_period, octaves, rng, gain=0.5, lacunarity=2):
    total = np.zeros((size, size), np.float32)
    amp, norm, period = 1.0, 0.0, base_period
    for _ in range(octaves):
        if period > size:
            break
        total += value_noise(size, period, rng) * amp
        norm += amp
        amp *= gain
        period *= lacunarity
    return total / norm


def ridged(size, base_period, octaves, rng):
    total = np.zeros((size, size), np.float32)
    amp, norm, period = 1.0, 0.0, base_period
    for _ in range(octaves):
        if period > size:
            break
        n = 1 - np.abs(value_noise(size, period, rng) * 2 - 1)
        total += n * n * amp
        norm += amp
        amp *= 0.5
        period *= 2
    return total / norm


def warp(field, dx, dy, strength):
    """Domain-warp a tileable field by displacement fields (in pixels)."""
    size = field.shape[0]
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32)
    sx = (xx + dx * strength) % size
    sy = (yy + dy * strength) % size
    x0 = np.floor(sx).astype(int)
    y0 = np.floor(sy).astype(int)
    fx = sx - x0
    fy = sy - y0
    x1 = (x0 + 1) % size
    y1 = (y0 + 1) % size
    return ((field[y0, x0] * (1 - fx) + field[y0, x1] * fx) * (1 - fy)
            + (field[y1, x0] * (1 - fx) + field[y1, x1] * fx) * fy)


def voronoi(size, cells, rng, jitter=0.9):
    """Tileable Voronoi. Returns (F1, F2, cell_id, edge_dist) in cell units."""
    pts = (rng.random((cells, cells, 2)) - 0.5) * jitter + 0.5
    ids = rng.random((cells, cells)).astype(np.float32)
    coords = (np.arange(size, dtype=np.float32) + 0.5) * cells / size
    yy, xx = np.meshgrid(coords, coords, indexing='ij')
    cx = np.floor(xx).astype(int)
    cy = np.floor(yy).astype(int)
    f1 = np.full((size, size), 1e9, np.float32)
    f2 = np.full((size, size), 1e9, np.float32)
    best_id = np.zeros((size, size), np.float32)
    best_p = np.zeros((size, size, 2), np.float32)
    cand = []
    for oy in (-1, 0, 1):
        for ox in (-1, 0, 1):
            nx = cx + ox
            ny = cy + oy
            p = pts[ny % cells, nx % cells]
            px = nx + p[..., 0]
            py = ny + p[..., 1]
            cand.append((px, py, ids[ny % cells, nx % cells]))
            d = np.sqrt((xx - px) ** 2 + (yy - py) ** 2)
            closer = d < f1
            f2 = np.where(closer, f1, np.minimum(f2, d))
            best_id = np.where(closer, ids[ny % cells, nx % cells], best_id)
            best_p[..., 0] = np.where(closer, px, best_p[..., 0])
            best_p[..., 1] = np.where(closer, py, best_p[..., 1])
            f1 = np.where(closer, d, f1)
    # true distance to the nearest cell border (perpendicular bisector distance)
    edge = np.full((size, size), 1e9, np.float32)
    for px, py, _ in cand:
        mx = (best_p[..., 0] + px) * 0.5
        my = (best_p[..., 1] + py) * 0.5
        vx = px - best_p[..., 0]
        vy = py - best_p[..., 1]
        ln = np.sqrt(vx * vx + vy * vy)
        valid = ln > 1e-5
        ln = np.where(valid, ln, 1)
        dist = ((mx - xx) * vx + (my - yy) * vy) / ln
        edge = np.where(valid, np.minimum(edge, dist), edge)
    return f1, f2, best_id, edge


# ---------------------------------------------------------------------------
# Map helpers
# ---------------------------------------------------------------------------

def blur(field, radius):
    """Cheap tileable box blur (3 passes ~ gaussian)."""
    out = field
    for _ in range(3):
        acc = np.zeros_like(out)
        for o in range(-radius, radius + 1):
            acc += np.roll(out, o, axis=1)
        out = acc / (2 * radius + 1)
        acc = np.zeros_like(out)
        for o in range(-radius, radius + 1):
            acc += np.roll(out, o, axis=0)
        out = acc / (2 * radius + 1)
    return out


def grain(size, rng, radius=1):
    """High-frequency mineral speckle (tileable)."""
    g = rng.random((size, size)).astype(np.float32)
    return blur(g, radius) if radius > 0 else g


def normal_from_height(h, strength):
    dx = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1)) * 0.5
    dy = (np.roll(h, -1, axis=0) - np.roll(h, 1, axis=0)) * 0.5
    nx = -dx * strength
    ny = dy * strength  # OpenGL convention: +Y is up in texture space (rows grow downward)
    nz = np.ones_like(h)
    ln = np.sqrt(nx * nx + ny * ny + nz * nz)
    return np.stack([nx / ln, ny / ln, nz / ln], -1)


def ao_from_height(h, radius, strength):
    cavity = blur(h, radius) - h
    return np.clip(1 - np.maximum(cavity, 0) * strength, 0, 1)


def lerp(a, b, t):
    t = t[..., None] if np.ndim(t) == 2 and np.ndim(a) == 3 else t
    return a + (b - a) * t


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


def rgb(hexstr):
    hexstr = hexstr.lstrip('#')
    c = np.array([int(hexstr[i:i + 2], 16) / 255 for i in (0, 2, 4)], np.float32)
    return c ** 2.2  # work in linear space


def save(name, albedo_lin, normal, ao, rough):
    """Writes two maps per material, so a shader needs only two texture slots:

    <name>_albedo.jpg  sRGB base color with the baked cavity AO multiplied in
    <name>_nr.jpg      R,G = tangent normal XY (OpenGL, +Y up), B = roughness.
                       The shader rebuilds normal Z as sqrt(1 - x^2 - y^2).
    """
    os.makedirs(OUT, exist_ok=True)
    shaded = albedo_lin * (ao[..., None] ** 0.8)
    srgb = np.clip(shaded, 0, 1) ** (1 / 2.2)
    Image.fromarray((srgb * 255 + 0.5).astype(np.uint8)).save(
        os.path.join(OUT, f'{name}_albedo.jpg'), quality=90, subsampling=0)
    nr = np.stack([normal[..., 0] * 0.5 + 0.5, normal[..., 1] * 0.5 + 0.5, np.clip(rough, 0, 1)], -1)
    Image.fromarray((np.clip(nr, 0, 1) * 255 + 0.5).astype(np.uint8)).save(
        os.path.join(OUT, f'{name}_nr.jpg'), quality=94, subsampling=0)
    print('wrote', name)


