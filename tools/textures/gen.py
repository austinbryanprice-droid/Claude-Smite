def flagstone(size, rng):
    """Irregular sandstone paving slabs with worn edges, grout, dirt and moss."""
    f1, f2, cid, edge = voronoi(size, 5, rng, jitter=0.85)
    wx = fbm(size, 8, 4, rng) * 2 - 1
    wy = fbm(size, 8, 4, rng) * 2 - 1
    edge = warp(edge, wx, wy, size * 0.006)
    cid = warp(cid, wx, wy, size * 0.006)
    grout_w = 0.018
    slab = smoothstep(grout_w * 0.4, grout_w * 2.2, edge)  # 0 in grout, 1 on slab top
    bevel = smoothstep(0.0, 0.16, edge)
    fine = fbm(size, 32, 5, rng)
    pits = smoothstep(0.62, 0.8, fbm(size, 64, 3, rng))
    cracks_src = ridged(size, 6, 4, rng)
    cracks = smoothstep(0.86, 0.97, cracks_src) * smoothstep(0.08, 0.2, edge)
    tilt = (cid - 0.5) * 0.15
    height = slab * (0.55 + bevel * 0.35 + tilt) + fine * 0.12 - pits * 0.05 - cracks * 0.12

    tones = [rgb('#c9b28c'), rgb('#b89c74'), rgb('#d6c4a1'), rgb('#a88f6b'), rgb('#bfa98a')]
    base = np.zeros((size, size, 3), np.float32)
    idx = np.floor(cid * len(tones)).astype(int) % len(tones)
    for i, t in enumerate(tones):
        base += (idx == i)[..., None] * t
    mott = fbm(size, 16, 5, rng)
    base *= (0.82 + mott * 0.36)[..., None]
    speck = grain(size, rng, 1)
    base *= (0.9 + (speck - 0.5) * 0.5)[..., None]
    height = height + (speck - 0.5) * 0.05 * slab
    # Packed earth between slabs: kept fairly light so the joints read as
    # soil rather than black voids that mirror the sky at grazing angles.
    grout = rgb('#8a7556') * (0.75 + fine[..., None] * 0.4)
    dirt_mask = np.clip((1 - bevel) * 0.6 + smoothstep(0.55, 0.8, fbm(size, 8, 4, rng)) * 0.35, 0, 1)
    base = lerp(base, base * rgb('#8a7458') * 1.4, dirt_mask * 0.45)
    moss_noise = fbm(size, 12, 4, rng)
    moss = smoothstep(0.5, 0.7, moss_noise) * (1 - smoothstep(0.0, 0.12, edge))
    albedo = lerp(grout, base, slab)
    albedo = lerp(albedo, rgb('#5a6033') * (0.7 + fine[..., None] * 0.6), moss * 0.6)
    albedo *= (1 - cracks * 0.45)[..., None]

    normal = normal_from_height(blur(height, 1), size / 120)
    ao = ao_from_height(height, max(2, size // 128), 2.2) * (1 - (1 - slab) * 0.15)
    rough = np.clip(0.78 + fine * 0.15 - slab * bevel * 0.06 + moss * 0.1 + (1 - slab) * 0.2, 0, 1)
    save('flagstone', albedo, normal, ao, rough)


def marble(size, rng):
    """White temple marble with soft grey/gold veins and slight weathering."""
    wx = fbm(size, 4, 6, rng) * 2 - 1
    wy = fbm(size, 4, 6, rng) * 2 - 1
    xx = np.mgrid[0:size, 0:size][1].astype(np.float32) / size
    yy = np.mgrid[0:size, 0:size][0].astype(np.float32) / size
    phase = (xx * 3 + yy * 2) + (wx * 1.4 + wy * 0.9)
    vein = np.abs(np.sin(phase * np.pi * 2))
    veins = 1 - smoothstep(0.0, 0.09, vein)
    veins *= 0.5 + 0.5 * smoothstep(0.3, 0.7, fbm(size, 4, 4, rng))
    phase2 = (xx * 7 - yy * 5) + fbm(size, 8, 5, rng) * 2.5
    fine_veins = 1 - smoothstep(0.0, 0.035, np.abs(np.sin(phase2 * np.pi * 2)))
    fine_veins *= smoothstep(0.4, 0.7, fbm(size, 4, 3, rng))
    cloud = fbm(size, 8, 6, rng)
    base = lerp(rgb('#ece6dc')[None, None, :], rgb('#f7f4ee')[None, None, :], cloud)
    base = lerp(base, rgb('#9e968c'), veins * 0.6)
    base = lerp(base, rgb('#c9b796'), fine_veins * 0.35)
    grime = smoothstep(0.55, 0.85, fbm(size, 6, 5, rng))
    base = lerp(base, base * rgb('#b6a58a') * 1.25, grime * 0.35)
    pits = smoothstep(0.7, 0.85, fbm(size, 128, 2, rng))
    height = cloud * 0.08 - veins * 0.04 - pits * 0.05 + fbm(size, 64, 3, rng) * 0.04
    normal = normal_from_height(height, size / 60)
    ao = ao_from_height(height, 2, 2.0)
    rough = np.clip(0.28 + grime * 0.25 + pits * 0.2 + veins * 0.05 + fbm(size, 32, 4, rng) * 0.08, 0, 1)
    save('marble', base, normal, ao, rough)


def sandstone_blocks(size, rng):
    """Ashlar wall of large sandstone blocks (4 courses), chipped and weathered."""
    rows = 4
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32) / size
    row = np.floor(yy * rows).astype(int)
    row_offsets = rng.random(rows)
    cols_per_row = rng.integers(2, 4, rows)
    u = (xx * cols_per_row[row] + row_offsets[row]) % 1e6
    col = np.floor(u).astype(int)
    fu = u - col
    fv = yy * rows - row
    block_id = ((row * 7919 + (col % cols_per_row[row]) * 104729) % 997) / 997.0
    wx = fbm(size, 16, 4, rng) * 2 - 1
    ex = np.minimum(fu, 1 - fu) / cols_per_row[row] * rows
    ey = np.minimum(fv, 1 - fv)
    edge = np.minimum(ex, ey) + wx * 0.02
    chips = smoothstep(0.55, 0.75, fbm(size, 24, 4, rng)) * 0.06
    mortar = smoothstep(0.006, 0.02 + chips, edge)
    bevel = smoothstep(0.0, 0.12, edge)
    fine = fbm(size, 32, 5, rng)
    strata = smoothstep(0.3, 0.7, np.sin((yy * 22 + fbm(size, 4, 4, rng) * 3) * np.pi * 2) * 0.5 + 0.5) * 0.5
    erosion = ridged(size, 8, 4, rng)
    speck = grain(size, rng, 1)
    pits = smoothstep(0.66, 0.8, fbm(size, 48, 3, rng))
    height = mortar * (0.6 + bevel * 0.3) + fine * 0.1 + strata * 0.02 - erosion * 0.1 * mortar + (speck - 0.5) * 0.06 - pits * 0.06

    tones = [rgb('#c8a878'), rgb('#bf9c6c'), rgb('#d1b488'), rgb('#b48f62')]
    base = np.zeros((size, size, 3), np.float32)
    idx = np.floor(block_id * len(tones)).astype(int) % len(tones)
    for i, t in enumerate(tones):
        base += (idx == i)[..., None] * t
    base *= (0.85 + fine * 0.25 + strata * 0.06 + (speck - 0.5) * 0.35 - pits * 0.15)[..., None]
    streaks = fbm(size, 4, 3, rng) * smoothstep(0.3, 1.0, 1 - fv)
    base = lerp(base, base * 0.75, smoothstep(0.5, 0.9, streaks) * 0.5)
    mortar_col = rgb('#9a8466') * (0.8 + fine[..., None] * 0.4)
    albedo = lerp(mortar_col, base, mortar)
    moss = smoothstep(0.6, 0.78, fbm(size, 10, 4, rng)) * (1 - bevel)
    albedo = lerp(albedo, rgb('#56602e'), moss * 0.7)
    normal = normal_from_height(height, size / 70)
    ao = ao_from_height(height, max(2, size // 128), 3.0)
    rough = np.clip(0.82 + fine * 0.12 - bevel * mortar * 0.04, 0, 1)
    save('sandstone_blocks', albedo, normal, ao, rough)


def rock(size, rng):
    """Layered cliff rock for terrain slopes, cliffs and boulders (triplanar)."""
    wx = fbm(size, 4, 5, rng) * 2 - 1
    wy = fbm(size, 4, 5, rng) * 2 - 1
    r = ridged(size, 4, 7, rng)
    r = warp(r, wx, wy, size * 0.05)
    yy = np.mgrid[0:size, 0:size][0].astype(np.float32) / size
    layers = np.sin((yy * 9 + wx * 0.6) * np.pi * 2) * 0.5 + 0.5
    layers = smoothstep(0.2, 0.8, layers)
    fine = fbm(size, 32, 5, rng)
    f1, f2, cid, edge = voronoi(size, 6, rng)
    facets = smoothstep(0.0, 0.25, edge)
    speck = grain(size, rng, 1)
    cracks = smoothstep(0.9, 0.98, ridged(size, 5, 4, rng))
    height = r * 0.6 + layers * 0.15 + fine * 0.15 + facets * 0.15 + (speck - 0.5) * 0.08 - cracks * 0.2
    base = lerp(rgb('#5f5850')[None, None, :], rgb('#8f8679')[None, None, :], np.clip(r * 1.2, 0, 1))
    base = lerp(base, rgb('#a2927a'), layers * 0.35)
    base *= (0.75 + fine * 0.35 + (speck - 0.5) * 0.4)[..., None]
    base *= (1 - cracks * 0.5)[..., None]
    lichen = smoothstep(0.62, 0.75, fbm(size, 16, 4, rng)) * smoothstep(0.4, 0.8, r)
    base = lerp(base, rgb('#8c8a5e'), lichen * 0.5)
    cav = 1 - smoothstep(0.1, 0.5, r)
    base = lerp(base, base * 0.55, cav * 0.6)
    normal = normal_from_height(height, size / 28)
    ao = ao_from_height(height, max(3, size // 96), 2.5)
    rough = np.clip(0.75 + fine * 0.15 + cav * 0.08 - lichen * 0.05, 0, 1)
    save('rock', base, normal, ao, rough)


def grass_ground(size, rng):
    """Ground under the grass blades: mixed live/dry grass, leaf litter, soil."""
    blades = ridged(size, 128, 3, rng)
    clump = fbm(size, 8, 5, rng)
    dry = smoothstep(0.45, 0.75, fbm(size, 6, 4, rng))
    soil = smoothstep(0.6, 0.78, fbm(size, 10, 5, rng))
    green = lerp(rgb('#3d5a1e')[None, None, :], rgb('#6d8a2c')[None, None, :], clump)
    yellow = lerp(rgb('#7c7a3a')[None, None, :], rgb('#a69a55')[None, None, :], clump)
    col = lerp(green, yellow, dry * 0.7)
    col *= (0.7 + blades * 0.5)[..., None]
    dirt = rgb('#5a4630') * (0.7 + fbm(size, 64, 3, rng)[..., None] * 0.5)
    col = lerp(col, dirt, soil * 0.8)
    height = blades * 0.4 * (1 - soil) + clump * 0.3 + fbm(size, 64, 3, rng) * 0.2 * soil
    normal = normal_from_height(height, size / 100)
    ao = ao_from_height(height, 2, 2.5)
    rough = np.clip(0.85 + soil * 0.1 - blades * 0.05, 0, 1)
    save('grass_ground', col, normal, ao, rough)


def dirt(size, rng):
    """Packed earth lane with embedded pebbles and tire-free footpath wear."""
    f1, f2, cid, edge = voronoi(size, 22, rng, jitter=1.0)
    wx = fbm(size, 64, 3, rng) * 2 - 1
    wy = fbm(size, 64, 3, rng) * 2 - 1
    f1 = warp(f1, wx, wy, size * 0.01)
    cid = warp(cid, wx, wy, size * 0.01)
    rad = 0.22 + (cid * 7 % 1) * 0.25
    keep = cid > 0.72
    pebble_h = np.sqrt(np.clip(1 - (f1 / rad) ** 2, 0, 1)) * keep * 0.6
    f1b, _, cidb, _ = voronoi(size, 70, rng, jitter=1.0)
    grit = np.sqrt(np.clip(1 - (f1b / 0.3) ** 2, 0, 1)) * (cidb > 0.6)
    soil = fbm(size, 8, 6, rng)
    cracks = smoothstep(0.88, 0.97, ridged(size, 5, 4, rng))
    height = soil * 0.25 + pebble_h * 0.5 + grit * 0.15 - cracks * 0.1
    col = lerp(rgb('#6b5236')[None, None, :], rgb('#8d7150')[None, None, :], soil)
    col *= (0.85 + fbm(size, 64, 3, rng) * 0.3)[..., None]
    peb_col = lerp(rgb('#6e6253')[None, None, :], rgb('#9c8f7a')[None, None, :], (cid * 13 % 1)[..., None] * np.ones(3))
    col = lerp(col, peb_col, np.clip(pebble_h * 2.5, 0, 1) * 0.8)
    col = lerp(col, rgb('#8f7f66'), grit * 0.3)
    col *= (0.9 + (grain(size, rng, 1) - 0.5) * 0.4)[..., None]
    col *= (1 - cracks * 0.4)[..., None]
    normal = normal_from_height(height, size / 80)
    ao = ao_from_height(height, 3, 3.0)
    rough = np.clip(0.9 - pebble_h * 0.2, 0, 1)
    save('dirt', col, normal, ao, rough)


def bark(size, rng):
    """Tree bark: deep vertical furrows between plated ridges, with lichen."""
    # Furrows are the contour lines of noise stretched along the trunk, so
    # they run long and wavy; a second, finer set splits the plates.
    wx = fbm(size, 4, 3, rng) * 2 - 1
    wy = fbm(size, 4, 3, rng) * 2 - 1
    major = warp(1 - np.abs(value_noise2(size, 26, 3, rng) * 2 - 1), wx, wy, size * 0.01)
    minor = warp(1 - np.abs(value_noise2(size, 64, 5, rng) * 2 - 1), wx, wy, size * 0.01)
    furrow = np.maximum(smoothstep(0.62, 0.95, major), smoothstep(0.8, 0.97, minor) * 0.7)
    plates = value_noise2(size, 18, 6, rng)
    h = 1 - furrow * 0.85 + (plates - 0.5) * 0.12 + (grain(size, rng, 1) - 0.5) * 0.08
    col = lerp(np.broadcast_to(rgb('#8a7158'), (size, size, 3)), rgb('#6e5a47'), fbm(size, 8, 4, rng))
    col = lerp(col, rgb('#2f241b'), furrow * 0.85)
    lichen = smoothstep(0.7, 0.82, fbm(size, 8, 5, rng)) * (1 - furrow)
    col = lerp(col, rgb('#8f9a5a'), lichen * 0.4)
    normal = normal_from_height(h, size / 40)
    ao = ao_from_height(h, 3, 2.5)
    rough = np.clip(0.82 + furrow * 0.12 - lichen * 0.05, 0, 1)
    save('bark', col, normal, ao, rough)


def _leaf_polygon(cx, cy, angle, length, width, bend=0.0, steps=14):
    """Outline of a pointed leaf from its base (cx, cy) toward `angle`."""
    left, right, mid = [], [], []
    ca, sa = np.cos(angle), np.sin(angle)
    for i in range(steps + 1):
        t = i / steps
        w = width * (np.sin(np.pi * t) ** 0.75) * (1 - 0.35 * t)
        along = t * length
        off = bend * length * t * t
        px = cx + ca * along - sa * off
        py = cy + sa * along + ca * off
        left.append((px - sa * w, py + ca * w))
        right.append((px + sa * w, py - ca * w))
        mid.append((px, py))
    return left, right, mid


def foliage_atlas(size, rng):
    """2x2 atlas of leaf sprigs with alpha, for the foliage cards.

    0: broadleaf sprig (canopy)   1: dense small-leaf clump (canopy, bushes)
    2: fern frond                  3: long blade leaves (undergrowth)
    Color is sRGB with gentle variation; the shader tints per instance.
    """
    from PIL import ImageDraw
    S = size * 2  # supersample, then downsample for clean edges
    img = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    T = S // 2

    def shade(base, k):
        return tuple(int(np.clip(c * k, 0, 255)) for c in base) + (255,)

    def leaf(ox, oy, x, y, ang, ln, wd, base, bend=0.0):
        left, right, mid = _leaf_polygon(ox + x, oy + y, ang, ln, wd, bend)
        d.polygon(left + mid[::-1], fill=shade(base, 1.08))
        d.polygon(right + mid[::-1], fill=shade(base, 0.86))
        d.line(mid, fill=shade(base, 0.7), width=max(1, int(wd * 0.12)))

    greens = [(86, 140, 46), (104, 158, 52), (72, 124, 40), (118, 166, 64), (92, 150, 58)]

    # 0: broadleaf sprig: a curved twig with alternating large leaves
    ox, oy = 0, 0
    stem = [(T * 0.5 + np.sin(t * 2) * T * 0.04, T * (0.97 - t * 0.85)) for t in np.linspace(0, 1, 20)]
    d.line(stem, fill=(70, 52, 34, 255), width=int(S * 0.006))
    for i in range(11):
        t = 0.12 + i * 0.08
        px, py = stem[min(19, int(t * 19))]
        side = 1 if i % 2 else -1
        ang = -np.pi / 2 + side * (0.9 - t * 0.4) + rng.normal() * 0.12
        ln = T * (0.30 - abs(t - 0.5) * 0.18) * (0.9 + rng.random() * 0.2)
        leaf(ox, oy, px, py, ang, ln, ln * 0.3, greens[rng.integers(len(greens))], bend=side * 0.08)
    leaf(ox, oy, *stem[-1], -np.pi / 2, T * 0.2, T * 0.06, greens[1])

    # 1: dense clump of small leaves filling the tile
    ox, oy = T, 0
    for _ in range(170):
        r = T * 0.42 * np.sqrt(rng.random())
        a = rng.random() * np.pi * 2
        x, y = T / 2 + np.cos(a) * r, T / 2 + np.sin(a) * r
        ln = T * (0.07 + rng.random() * 0.06)
        leaf(ox, oy, x, y, a + rng.normal() * 0.6, ln, ln * 0.42, greens[rng.integers(len(greens))])

    # 2: fern frond: a rachis with paired pinnae shrinking toward the tip
    ox, oy = 0, T
    rach = [(T * 0.5 + np.sin(t * 2.2) * T * 0.08, T * (0.98 - t * 0.92)) for t in np.linspace(0, 1, 40)]
    d.line(rach, fill=(64, 92, 34, 255), width=int(S * 0.004))
    for i in range(2, 38, 2):
        t = i / 39
        px, py = rach[i]
        ln = T * 0.36 * np.sin(np.pi * (0.15 + t * 0.85)) ** 0.7 * (1 - t * 0.55)
        for side in (-1, 1):
            ang = -np.pi / 2 + side * (1.35 - t * 0.55)
            leaf(ox, oy, px, py, ang, ln, ln * 0.16, greens[(i // 2 + side) % len(greens)], bend=-side * 0.1)

    # 3: long arching blades from a common base (undergrowth, palms)
    ox, oy = T, T
    for i in range(9):
        a = -np.pi / 2 + (i - 4) * 0.2 + rng.normal() * 0.05
        ln = T * (0.75 - abs(i - 4) * 0.07)
        leaf(ox, oy, T * 0.5, T * 0.98, a, ln, T * 0.035, greens[i % len(greens)], bend=(i - 4) * 0.06)

    img = img.resize((size, size), Image.LANCZOS)
    # Bleed color into transparent texels so mipmaps don't darken leaf edges.
    arr = np.asarray(img).astype(np.float32)
    rgbch, a = arr[..., :3], arr[..., 3:] / 255
    acc = rgbch * a
    wsum = a.copy()
    for _ in range(6):
        acc = (acc + np.roll(acc, 1, 0) + np.roll(acc, -1, 0) + np.roll(acc, 1, 1) + np.roll(acc, -1, 1))
        wsum = (wsum + np.roll(wsum, 1, 0) + np.roll(wsum, -1, 0) + np.roll(wsum, 1, 1) + np.roll(wsum, -1, 1))
    bled = acc / np.maximum(wsum, 1e-4)
    out = np.where(a > 0.5, rgbch, bled)
    out = np.concatenate([np.clip(out, 0, 255), arr[..., 3:]], -1).astype(np.uint8)
    os.makedirs(OUT, exist_ok=True)
    Image.fromarray(out, 'RGBA').save(os.path.join(OUT, 'foliage_atlas.png'), optimize=True)
    print('wrote foliage_atlas')


